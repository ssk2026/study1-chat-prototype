create extension if not exists pgcrypto;

create table if not exists public.sessions (
  id uuid primary key default gen_random_uuid(),
  client_session_id text not null unique,
  participant_id text not null,
  task_code text not null check (task_code in ('TASK_1_DESERT', 'TASK_2_CONFLICT')),
  condition_code text not null,
  study_version text not null,
  status text not null default 'active' check (status in ('active', 'complete', 'withdrawn', 'error')),
  metadata jsonb not null default '{}'::jsonb,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.sessions(id) on delete cascade,
  client_message_id text not null,
  task_code text not null,
  role text not null check (role in ('user', 'assistant', 'system')),
  content text not null,
  turn_index integer not null,
  model text,
  openai_response_id text,
  openai_request_id text,
  latency_ms integer,
  usage jsonb not null default '{}'::jsonb,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (session_id, client_message_id)
);

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.sessions(id) on delete cascade,
  event_type text not null,
  payload jsonb not null default '{}'::jsonb,
  client_occurred_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.task1_rankings (
  session_id uuid primary key references public.sessions(id) on delete cascade,
  initial_ranking text[],
  ai_ranking text[],
  final_ranking text[],
  ranking_moves jsonb not null default '[]'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.task2_opinions (
  session_id uuid primary key references public.sessions(id) on delete cascade,
  initial_choice text check (initial_choice in ('man', 'woman', 'equal')),
  initial_reason text,
  ai_position text check (ai_position in ('man', 'woman')),
  final_choice text check (final_choice in ('man', 'woman', 'equal')),
  final_reason text,
  changed boolean,
  updated_at timestamptz not null default now()
);

create index if not exists messages_session_turn_idx on public.messages(session_id, turn_index, created_at);
create index if not exists events_session_created_idx on public.events(session_id, created_at);
create index if not exists sessions_task_status_idx on public.sessions(task_code, status, created_at);

alter table public.sessions enable row level security;
alter table public.messages enable row level security;
alter table public.events enable row level security;
alter table public.task1_rankings enable row level security;
alter table public.task2_opinions enable row level security;

revoke all on table public.sessions from anon, authenticated;
revoke all on table public.messages from anon, authenticated;
revoke all on table public.events from anon, authenticated;
revoke all on table public.task1_rankings from anon, authenticated;
revoke all on table public.task2_opinions from anon, authenticated;
revoke all on sequence public.messages_id_seq from anon, authenticated;
revoke all on sequence public.events_id_seq from anon, authenticated;

comment on table public.sessions is 'Anonymous research sessions. Direct browser access is intentionally disabled.';
comment on table public.messages is 'Participant and AI turns, written only by the server-side API.';

